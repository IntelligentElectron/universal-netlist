/**
 * The agent skill for the query command line, rendered from the tool registry.
 *
 * The skill follows the Agent Skills specification (agentskills.io): a short
 * `SKILL.md` an agent loads when the skill applies, and `references/tools.md`
 * with every tool's description and flags, which it reads when it needs them.
 * Both are this module's output, written by `npm run gen:skill`. A test
 * compares them with the committed files, so a change to a tool's description
 * or arguments fails until the skill is regenerated, and the skill never
 * describes a tool other than the one that runs.
 */

import { SERVER_INSTRUCTIONS } from "../descriptions.js";
import { GITHUB_REPO, NPM_PACKAGE } from "../version.js";
import { TOOLS } from "../tools/index.js";
import { flagsOf, usageLine } from "./query.js";

/** The skill's directory, from the repository root. */
export const SKILL_DIR = "plugins/universal-netlist/skills/universal-netlist";

/** Where the generated skill lives, from the repository root. */
export const SKILL_PATH = `${SKILL_DIR}/SKILL.md`;

/** The tool reference the skill points to, from the repository root. */
export const TOOLS_REFERENCE_PATH = `${SKILL_DIR}/references/tools.md`;

const GENERATED =
  "<!-- Generated by `npm run gen:skill` from the tool registry in src/tools/index.ts. Edit the tools, not this file. -->";

const SKILL_DESCRIPTION =
  "Query EDA netlists from the shell with the universal-netlist command line: Cadence OrCAD .DSN, " +
  "Altium .PrjPcb, KiCad .kicad_pro and Universal Netlist .netlist.json. Finds designs, searches " +
  "nets and components, traces connectivity across passives (XNETs), and runs electrical rule " +
  "checks. Use when reviewing a schematic or circuit and no universal-netlist MCP server is " +
  "connected, as in a sandbox or container.";

/**
 * The server's conventions, as they apply to the command line: every bullet
 * of SERVER_INSTRUCTIONS' Conventions section but the one about MCP tools.
 */
const conventions = (): string[] => {
  const section = SERVER_INSTRUCTIONS.split("## Conventions")[1] ?? "";
  return section
    .split("\n")
    .filter((line) => line.startsWith("- ") && !line.startsWith("- Read designs only"))
    .map(asFlags);
};

/** Every argument name any tool takes. */
const argumentNames = (): Set<string> =>
  new Set(TOOLS.flatMap((tool) => flagsOf(tool).map((flag) => flag.name)));

/**
 * MCP argument spellings in prose, as the command line writes them:
 * `include_dns=true` is `--include_dns`. Only argument names are rewritten, so
 * a result field such as `dns=true` stays as it is.
 */
const asFlags = (text: string): string => {
  const names = argumentNames();
  return text.replace(/`?\b(\w+)=(true|false)\b`?/g, (match, name: string, value: string) => {
    if (!names.has(name)) return match;
    const flag = value === "true" ? `--${name}` : `--${name}=false`;
    return match.startsWith("`") ? `\`${flag}\`` : flag;
  });
};

/**
 * A description's first sentence, on one line, for the skill's tool table: it
 * says what the tool is for, which is what an agent picks a tool by.
 */
const firstSentence = (text: string): string => {
  const flat = text.replace(/\s+/g, " ").trim();
  // A full stop ends the sentence, unless it ends an abbreviation such as e.g.
  const end = [...flat.matchAll(/\.(\s|$)/g)].find(
    (match) => !/\b(e\.g|i\.e|etc)$/i.test(flat.slice(0, match.index))
  )?.index;
  return (end === undefined ? flat : flat.slice(0, end + 1)).replace(/\|/g, "\\|");
};

const flagLine = (flag: ReturnType<typeof flagsOf>[number]): string => {
  const kind =
    flag.kind === "array"
      ? "text, repeat the flag for each"
      : flag.kind === "boolean"
        ? "true or false; alone means true"
        : flag.kind;
  const notes = [kind];
  if (flag.required) notes.unshift("required");
  if (flag.default !== undefined) notes.push(`default ${JSON.stringify(flag.default)}`);
  if (flag.name === "design") notes.push("or the first argument");
  const description = flag.description ? ` ${flag.description}.`.replace(/\.\.$/, ".") : "";
  return `- \`--${flag.name}\` (${notes.join("; ")}).${description}`;
};

