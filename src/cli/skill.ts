/** Every tool's description, usage line and flags, which the skill points to. */
export const renderToolsReference = (): string => {
  const lines: string[] = [
    GENERATED,
    "",
    "# universal-netlist tools",
    "",
    "Each tool is a command: `universal-netlist <tool> [design] --flag value`. The descriptions are the MCP tools' own; where one says an unknown argument is dropped, the command line refuses it instead, with exit 2.",
  ];
  for (const tool of TOOLS) {
    lines.push(
      "",
      `## ${tool.name}`,
      "",
      asFlags(tool.description),
      "",
      "```bash",
      usageLine(tool),
      "```",
      ""
    );
    for (const flag of flagsOf(tool)) lines.push(flagLine(flag));
  }
  return `${lines.join("\n")}\n`;
};
