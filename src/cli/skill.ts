/**
 * The agent skill for the query command line, rendered from the tool registry.
 *
 * The skill follows the Agent Skills specification (agentskills.io): one
 * `SKILL.md` with the command line's usage and every tool's description and
 * flags, which an agent reads before running a tool. It is this module's
 * output, written by `npm run gen:skill`. A test compares it with the
 * committed file, so a change to a tool's description or arguments fails until
 * the skill is regenerated, and the skill never describes a tool other than the
 * one that runs.
 */

import { SERVER_INSTRUCTIONS } from "../descriptions.js";
import { GITHUB_REPO, NPM_PACKAGE } from "../version.js";
import { TOOLS } from "../tools/index.js";
import { CLI_ONLY_TOOLS, flagsOf } from "./query.js";

/** The skill's directory, from the repository root. */
export const SKILL_DIR = "plugins/universal-netlist/skills/universal-netlist";

/** Where the generated skill lives, from the repository root. */
export const SKILL_PATH = `${SKILL_DIR}/SKILL.md`;

const GENERATED =
  "<!-- Generated by `npm run gen:skill` from the tool registry in src/tools/index.ts. Edit the tools, not this file. -->";

const SKILL_DESCRIPTION =
  "Query EDA netlists from the shell with the universal-netlist command line: Cadence OrCAD .DSN, " +
  "Altium .PrjPcb, KiCad .kicad_pro and Universal Netlist .netlist.json. Finds designs, searches " +
  "nets and components, traces connectivity across passives (XNETs), and runs electrical rule " +
  "checks. Use when reviewing a schematic or circuit and no universal-netlist MCP server is " +
  "connected, as in a sandbox or container.";

/**
 * The server's conventions, as they apply to the command line: every bullet
 * of SERVER_INSTRUCTIONS' Conventions section but the one about MCP tools.
 */
const conventions = (): string[] => {
  const section = SERVER_INSTRUCTIONS.split("## Conventions")[1] ?? "";
  return section
    .split("\n")
    .filter((line) => line.startsWith("- ") && !line.startsWith("- Read designs only"))
    .map(asFlags);
};

/** Every argument name any tool takes. */
const argumentNames = (): Set<string> =>
  new Set(TOOLS.flatMap((tool) => flagsOf(tool).map((flag) => flag.name)));

/**
 * MCP argument spellings in prose, as the command line writes them:
 * `include_dns=true` is `--include_dns`. Only argument names are rewritten, so
 * a result field such as `dns=true` stays as it is.
 */
const asFlags = (text: string): string => {
  const names = argumentNames();
  return text.replace(/`?\b(\w+)=(true|false)\b`?/g, (match, name: string, value: string) => {
    if (!names.has(name)) return match;
    const flag = value === "true" ? `--${name}` : `--${name}=false`;
    return match.startsWith("`") ? `\`${flag}\`` : flag;
  });
};

const flagLine = (flag: ReturnType<typeof flagsOf>[number]): string => {
  const kind =
    flag.kind === "array"
      ? "text, repeat the flag for each"
      : flag.kind === "boolean"
        ? "true or false; alone means true"
        : flag.kind;
  const notes = [kind];
  if (flag.required) notes.unshift("required");
  if (flag.default !== undefined) notes.push(`default ${JSON.stringify(flag.default)}`);
  const description = flag.description ? ` ${flag.description}.`.replace(/\.\.$/, ".") : "";
  return `- \`--${flag.name}\` (${notes.join("; ")}).${description}`;
};

/**
 * Flags every tool but list_designs takes, described once at the top of the
 * skill's Tools section instead of under each tool.
 */
export const SHARED_FLAGS = ["design", "design_variant"] as const;

const isShared = (name: string): boolean => (SHARED_FLAGS as readonly string[]).includes(name);

/** The shared flags' lines, rendered from the first tool that takes them, as every flag is. */
const sharedFlagLines = (): string[] =>
  SHARED_FLAGS.map((name) => {
    const flag = TOOLS.flatMap((tool) => flagsOf(tool)).find((f) => f.name === name);
    return flag ? flagLine(flag) : `- \`--${name}\`.`;
  });

/**
 * The skill's frontmatter: the Agent Skills fields, and only those, so every
 * host reads it. Each value is written as a JSON string, which is a YAML
 * double-quoted scalar, because a plain one cannot hold the `: ` the
 * description does and strict YAML readers (gh skill) refuse it.
 */
const FRONTMATTER = {
  name: "universal-netlist",
  description: SKILL_DESCRIPTION,
  license: "Apache-2.0",
  compatibility:
    "Requires a shell and the universal-netlist command line (the standalone binary, or Node.js 22.15+ for npx).",
};

/** The skill's Markdown. */
export const renderSkill = (): string => {
  const lines: string[] = [
    "---",
    ...Object.entries(FRONTMATTER).map(([key, value]) => `${key}: ${JSON.stringify(value)}`),
    "---",
    "",
    GENERATED,
    "",
    "# Universal Netlist command line",
    "",
    "`universal-netlist` answers the same queries as the universal-netlist MCP server, one shell command each. When that MCP server is connected, use its tools instead.",
    "",
    "## Install",
    "",
    "Check for it with `universal-netlist --version`. If it is missing, either install the standalone binary:",
    "",
    "```bash",
    `curl -fsSL https://raw.githubusercontent.com/${GITHUB_REPO}/main/install.sh | bash`,
    "```",
    "",
    "or run it through npm without installing, writing `npx -y " +
      NPM_PACKAGE +
      "` wherever this guide writes `universal-netlist`.",
    "",
    "## Usage",
    "",
    "```bash",
    "universal-netlist <tool> [design] --flag value ...",
    "universal-netlist <tool> --help     # the tool's description and every flag",
    "universal-netlist --help            # every tool",
    "```",
    "",
    "- The tool is its name below, in snake_case. Flags are its arguments, spelled exactly: `--net_name`, not `--net-name`.",
    "- The design may be the first argument, or `--design`.",
    "- A flag takes the next word, or `--flag=value`. A value that starts with a dash needs `=`: `--net_name=-12V`.",
    "- A boolean flag alone means true: `--include_dns`. `--include_dns false` and `--include_dns=false` turn it off.",
    "- A list repeats its flag: `--skip_types C --skip_types L`.",
    "- Quote regex patterns for the shell: `--pattern '^VCC'`.",
    "",
    "## Output and exit codes",
    "",
    "The result is the tool's JSON on stdout: indented in a terminal, one compact line otherwise, so pipe it to `jq` when it is long.",
    "",
    "| Exit | Meaning |",
    "|------|---------|",
    "| 0 | The result answers the query |",
    "| 1 | The result has an `error` field; its message names the tool that finds what you were looking for |",
    "| 2 | Usage error: an unknown or missing flag, or a value of the wrong kind. The message and a usage line are on stderr |",
    "",
    "## Parse cache",
    "",
    "Parsing a large design takes a second or two; a query on a parsed design takes milliseconds. Each call is a new process, so turn on the disk cache when you will query a design more than once: `--cache` on a call, or `export UNIVERSAL_NETLIST_CACHE=1` for the session. A parse is reused until a file the design reads changes, and the cache never fails a query. `UNIVERSAL_NETLIST_CACHE_DIR` puts it in a directory of your choice, such as a mounted volume.",
    "",
    "## Workflow",
    "",
    "1. `universal-netlist list_designs --path <dir>` finds the designs, gives the path to query, and lists each design's `design_variants`.",
    "2. `search_nets` and `search_components_by_*` find things by pattern.",
    "3. `query_component` and `query_xnet_by_*` give detail and connectivity.",
    "4. `run_erc` runs the electrical rule checks.",
    "",
    "Answer questions about a design with these query tools. `export_design` writes a whole design as a `.netlist.json` file, and is only for a program that post-processes the netlist in that format; see [Command-line-only tools](#command-line-only-tools).",
    "",
    "```bash",
    "universal-netlist list_designs --path ./hardware",
    "universal-netlist search_nets hardware/board.DSN --pattern '^VCC'",
    "universal-netlist query_xnet_by_net_name hardware/board.DSN --net_name SPI_CLK --skip_types C",
    "```",
    "",
    "## Conventions",
    "",
    ...conventions(),
    "- Read design files only through these commands, not by parsing them yourself, and never run `universal-netlist update` or `universal-netlist uninstall`: they replace or remove the binary",
    "",
    "## Tools",
    "",
    "Each description is the MCP tool's own.",
    "",
    "Every tool but `list_designs` also takes these two flags, not repeated below; `--design` may be the first argument instead:",
    "",
    ...sharedFlagLines(),
  ];
  for (const tool of TOOLS) {
    lines.push("", `### ${tool.name}`, "", asFlags(tool.description));
    const own = flagsOf(tool).filter((flag) => !isShared(flag.name));
    if (own.length > 0) lines.push("", ...own.map(flagLine));
  }
  lines.push(
    "",
    "## Command-line-only tools",
    "",
    "These tools are not offered by the MCP server. Each takes the shared flags above as well as its own, and prints its result as the query tools do.",
    "",
    "To answer a question about a design, run a query tool: it reads the design directly and returns only what was asked, at a fraction of the cost of reading a whole-netlist file. Export a design only when the netlist itself must be post-processed in Universal Netlist format, by a script or another program, or kept as a snapshot of one build."
  );
  for (const tool of CLI_ONLY_TOOLS) {
    lines.push("", `### ${tool.name}`, "", asFlags(tool.description));
    const own = flagsOf(tool).filter((flag) => !isShared(flag.name));
    if (own.length > 0) lines.push("", ...own.map(flagLine));
  }
  return `${lines.join("\n")}\n`;
};
